    def payload_gravity_wrench():
        weighted_com = np.zeros(
            3
        )

        for body_id in payload_body_ids:
            weighted_com += (
                mj_model.body_mass[
                    body_id
                ]
                * mj_data.xipos[
                    body_id
                ]
            )

        if payload_mass > 1e-12:
            payload_com = (
                weighted_com
                / payload_mass
            )
        else:
            payload_com = (
                mj_data.site_xpos[
                    ft_site_id
                ].copy()
            )

        sensor_position = (
            mj_data.site_xpos[
                ft_site_id
            ].copy()
        )

        gravity_world = np.array(
            mj_model.opt.gravity
        )

        force_world = (
            -payload_mass
            * gravity_world
        )

        torque_world = np.cross(
            payload_com
            - sensor_position,
            force_world,
        )

        R_sensor_world = (
            mj_data.site_xmat[
                ft_site_id
            ]
            .reshape(
                3,
                3,
            )
            .copy()
        )

        return np.concatenate(
            [
                R_sensor_world.T
                @ force_world,
                R_sensor_world.T
                @ torque_world,
            ]
        )

    def sensor_wrench_to_external_world(
        wrench_sensor,
    ):
        R_sensor_world = (
            mj_data.site_xmat[
                ft_site_id
            ]
            .reshape(
                3,
                3,
            )
            .copy()
        )

        return np.concatenate(
            [
                -R_sensor_world
                @ wrench_sensor[
                    :3
                ],
                -R_sensor_world
                @ wrench_sensor[
                    3:
                ],
            ]
        )

