    # -----------------------------------------------------------------------
    # 6D Cartesian inverse-dynamics controller
    # -----------------------------------------------------------------------
    def cartesian_controller(
        p_des,
        R_des,
        v_linear_des,
        a_linear_des,
        external_world_wrench,
    ):
        q_pin = mj_q_to_pin(
            mj_data.qpos,
            mj_model,
            pin_model,
        )

        v_pin = mj_v_to_pin(
            mj_data.qvel,
            mj_model,
            pin_model,
        )

        pin.forwardKinematics(
            pin_model,
            pin_data,
            q_pin,
            v_pin,
        )

        pin.computeJointJacobians(
            pin_model,
            pin_data,
            q_pin,
        )

        pin.computeJointJacobiansTimeVariation(
            pin_model,
            pin_data,
            q_pin,
            v_pin,
        )

        pin.updateFramePlacements(
            pin_model,
            pin_data,
        )

        pose = pin_data.oMf[
            tcp_frame_id
        ]

        p = pose.translation.copy()
        R = pose.rotation.copy()

        J = pin.getFrameJacobian(
            pin_model,
            pin_data,
            tcp_frame_id,
            pin.LOCAL_WORLD_ALIGNED,
        )

        dJ = pin.getFrameJacobianTimeVariation(
            pin_model,
            pin_data,
            tcp_frame_id,
            pin.LOCAL_WORLD_ALIGNED,
        )

        spatial_velocity = (
            J
            @ v_pin
        )

        v_linear = spatial_velocity[
            :3
        ]

        omega = spatial_velocity[
            3:
        ]

        e_position = (
            p_des
            - p
        )

        e_orientation = pin.log3(
            R_des
            @ R.T
        )

        a_cmd = (
            a_linear_des
            + KP_LINEAR
            * e_position
            + KD_LINEAR
            * (
                v_linear_des
                - v_linear
            )
        )

        alpha_cmd = (
            KP_ANGULAR
            * e_orientation
            - KD_ANGULAR
            * omega
        )

        desired_spatial_acc = np.concatenate(
            [
                a_cmd,
                alpha_cmd,
            ]
        )

        rhs = (
            desired_spatial_acc
            - dJ
            @ v_pin
        )

        singular_values = np.linalg.svd(
            J,
            compute_uv=False,
        )

        sigma_min = float(
            singular_values[-1]
        )

        condition = float(
            singular_values[0]
            / singular_values[-1]
        )

        use_exact = (
            sigma_min
            > EXACT_SIGMA_MIN
            and condition
            < EXACT_CONDITION_MAX
        )

        if use_exact:
            try:
                qdd = np.linalg.solve(
                    J,
                    rhs,
                )
            except np.linalg.LinAlgError:
                use_exact = False

        if not use_exact:
            qdd = (
                J.T
                @ np.linalg.solve(
                    J
                    @ J.T
                    + DLS_LAMBDA**2
                    * np.eye(6),
                    rhs,
                )
            )

        tau_pin = pin.rnea(
            pin_model,
            pin_data,
            q_pin,
            v_pin,
            qdd,
        )

        # External wrench is referenced at the FT300 frame.
        J_ft = pin.getFrameJacobian(
            pin_model,
            pin_data,
            ft_frame_id,
            pin.LOCAL_WORLD_ALIGNED,
        )

        tau_pin -= (
            J_ft.T
            @ external_world_wrench
        )

        tau_mj = pin_tau_to_mj(
            tau_pin,
            pin_model,
            mj_model,
        )

        tau_act = (
            tau_mj
            - mj_data.qfrc_passive[
                :6
            ]
        )

        saturated = False

        for actuator_id in range(
            6
        ):
            low, high = (
                mj_model.actuator_ctrlrange[
                    actuator_id
                ]
            )

            clipped = np.clip(
                tau_act[
                    actuator_id
                ],
                low,
                high,
            )

            if abs(
                clipped
                - tau_act[
                    actuator_id
                ]
            ) > 1e-12:
                saturated = True

            tau_act[
                actuator_id
            ] = clipped

        mj_data.ctrl[
            :6
        ] = tau_act

        return (
            p,
            R,
            e_position,
            e_orientation,
            sigma_min,
            condition,
            tau_act,
            saturated,
        )

