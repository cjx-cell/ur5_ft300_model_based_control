#!/usr/bin/env python3
"""97A - UR5 unknown-surface low-force tactile exploration.

Goal
----
Acquire a 3D surface point cloud using only:
- known XY raster layout,
- a fixed probe orientation,
- FT300 feedback,
- 1 N vertical probing force.

The controller DOES NOT use:
- analytical ellipsoid height,
- analytical surface normals,
- step-89 Z coordinates,
- step-89 desired orientations.

The file `89_raster_scan_path.npz` is used only for:
- XY raster coordinates,
- row_id,
- phase.

The measured TCP Z is generated by the force-admittance loop and saved as the
learned surface height.

Inputs
------
ur5_ft300_inspection_workcell.xml
ur5_ft300_inspection.urdf
89_raster_scan_path.npz
93_ur5_scan_ik_solutions.npz   # seed only; no surface geometry is read from it

Outputs
-------
97_unknown_surface_points.csv
97_unknown_surface_points.npz
"""

