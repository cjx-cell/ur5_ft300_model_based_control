def sync_pinocchio_numerical_terms(
    pin_model,
    mj_model,
):
    for pin_joint_id in range(
        1,
        pin_model.njoints,
    ):
        name = pin_model.names[
            pin_joint_id
        ]

        mj_joint_id = mujoco.mj_name2id(
            mj_model,
            mujoco.mjtObj.mjOBJ_JOINT,
            name,
        )

        if mj_joint_id < 0:
            raise RuntimeError(
                f"MuJoCo缺少关节: {name}"
            )

        pin_v = pin_model.idx_vs[
            pin_joint_id
        ]

        mj_v = int(
            mj_model.jnt_dofadr[
                mj_joint_id
            ]
        )

        pin_model.armature[
            pin_v
        ] = mj_model.dof_armature[
            mj_v
        ]

        pin_model.damping[
            pin_v
        ] = mj_model.dof_damping[
            mj_v
        ]

        pin_model.friction[
            pin_v
        ] = mj_model.dof_frictionloss[
            mj_v
        ]


